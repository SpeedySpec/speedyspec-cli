#!/usr/bin/env bash
# Builds the static PHP that speedyspec embeds.
#
# Downloads a pinned static-php-cli (`spc`) binary for the host, writes
# craft.yml from the version in ./php-version, and runs `spc craft`. The result
# is .php-build/buildroot with lib/libphp.a (embed SAPI) and bin/php-config.
# See docs/php-embed.md for why each setting is what it is.
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
build_dir="$repo/.php-build"

# static-php-cli 2.8.6, nightly channel on dl.static-php.dev (published
# 2026-08-22). The nightly URL is mutable; the checksum is what pins the
# version. A mismatch means upstream moved: re-pin deliberately.
spc_base_url="https://dl.static-php.dev/static-php-cli/spc-bin/nightly"

case "$(uname -s)-$(uname -m)" in
    Darwin-arm64)   spc_name="spc-macos-aarch64";  spc_sha256="9eba2e6e0d1aebabd6ff8efc6711dd0bad335ba41e29ce36e06ea5a6c5d57731" ;;
    Linux-x86_64)   spc_name="spc-linux-x86_64";   spc_sha256="c138f3e4a68479597e11ca14d5209346c54758ccd09005e7a6a6f1e63b7f9f71" ;;
    Linux-aarch64)  spc_name="spc-linux-aarch64";  spc_sha256="26f483093b97da2925e4e993036c59509eab28656346b505d2d0a11271faae99" ;;
    *) echo "build-php.sh: unsupported host $(uname -s)-$(uname -m)" >&2; exit 1 ;;
esac

sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1
    fi
}

mkdir -p "$build_dir"
spc="$build_dir/spc"

if [ ! -x "$spc" ] || [ "$(sha256_of "$spc")" != "$spc_sha256" ]; then
    echo "build-php.sh: downloading $spc_name"
    curl -fsSL -o "$spc.download" "$spc_base_url/$spc_name"
    actual="$(sha256_of "$spc.download")"
    if [ "$actual" != "$spc_sha256" ]; then
        rm -f "$spc.download"
        echo "build-php.sh: checksum mismatch for $spc_name" >&2
        echo "  expected $spc_sha256" >&2
        echo "  actual   $actual" >&2
        exit 1
    fi
    chmod +x "$spc.download"
    mv "$spc.download" "$spc"
fi

php_version="$(tr -d '[:space:]' < "$repo/php-version")"
extensions="ctype,curl,filter,mbstring,openssl,phar,tokenizer,zip,zlib"

# `cli` is built only because ext-php-rs's build script runs `php -i` to read
# the API version and thread safety. The CLI binary is never shipped.
cat > "$repo/craft.yml" <<EOF
# Generated by scripts/build-php.sh from ./php-version. Do not edit by hand.
php-version: "$php_version"
extensions: "$extensions"
sapi:
  - embed
  - cli
EOF

# A buildroot made from this exact craft.yml is reused (CI restores it from
# cache); anything else is rebuilt.
stamp="$build_dir/buildroot/.craft.yml"
if [ -f "$build_dir/buildroot/lib/libphp.a" ] && cmp -s "$repo/craft.yml" "$stamp"; then
    echo "build-php.sh: $build_dir/buildroot is up to date"
    exit 0
fi

cd "$build_dir"
"$spc" craft "$repo/craft.yml"

if [ ! -f "$build_dir/buildroot/lib/libphp.a" ]; then
    echo "build-php.sh: $build_dir/buildroot/lib/libphp.a was not produced" >&2
    exit 1
fi

# `php-config --libs` omits libraries that spc's dependencies need (libxml2,
# libiconv, macOS frameworks), so record spc's own list for build.rs.
"$spc" spc-config "$extensions" --libs --no-motd > "$build_dir/buildroot/link-flags.txt"

cp "$repo/craft.yml" "$stamp"
echo "build-php.sh: built PHP $("$build_dir/buildroot/bin/php-config" --version) in $build_dir/buildroot"
